// Bundles migrations/*.sql into src/migrations.generated.ts so apps can import them without filesystem paths.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
const files = readdirSync(new URL("../migrations/", import.meta.url)).filter((f) => f.endsWith(".sql")).sort();
const entries = files.map((f) => `  { name: ${JSON.stringify(f)}, sql: ${JSON.stringify(readFileSync(new URL(`../migrations/${f}`, import.meta.url), "utf8"))} },`);
writeFileSync(new URL("../src/migrations.generated.ts", import.meta.url),
  `// GENERATED by scripts/gen-migrations.mjs from migrations/*.sql. Do not edit by hand.\nexport const MIGRATIONS: { name: string; sql: string }[] = [\n${entries.join("\n")}\n];\n`);
console.log(`bundled ${files.length} migration(s)`);
